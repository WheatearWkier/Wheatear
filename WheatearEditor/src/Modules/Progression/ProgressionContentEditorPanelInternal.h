        inline std::string RecordId(const YAML::Node& node, size_t index)
        {
            const std::string id = ScalarText(node["id"]);
            return id.empty() ? "__record_" + std::to_string(index + 1) : id;
        }

        inline std::string RecordTitle(const YAML::Node& node, size_t index)
        {
            const std::string id = RecordId(node, index);
            const std::string name = ScalarText(node["name"]);
            return name.empty() ? id : id + "  " + name;
        }

        inline bool RecordIdExists(const YAML::Node& sequence, const std::string& id)
        {
            if (!sequence || !sequence.IsSequence())
                return false;

            for (size_t i = 0; i < sequence.size(); ++i)
            {
                if (ScalarText(sequence[i]["id"]) == id)
                    return true;
            }
            return false;
        }

        inline std::string MakeUniqueRecordId(const YAML::Node& sequence, const std::string& base)
        {
            if (!RecordIdExists(sequence, base))
                return base;

            for (int i = 2; i < 10000; ++i)
            {
                const std::string candidate = base + "_" + std::to_string(i);
                if (!RecordIdExists(sequence, candidate))
                    return candidate;
            }
            return base + "_copy";
        }


