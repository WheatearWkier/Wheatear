        inline void AppendDelimitedToken(std::string& value, const std::string& token)
        {
            if (token.empty())
                return;

            if (!value.empty())
            {
                const char last = value.back();
                if (last != ' ' && last != '/' && last != '\n')
                    value += " / ";
                else if (last == ' ')
                    value += "/ ";
            }
            value += token;
        }

        inline bool DrawAppendTokenButton(const char* label,
            std::string& value,
            const std::vector<std::string>& choices,
            const char* prefix = "",
            const char* suffix = "")
        {
            const bool hasChoices = !choices.empty();
            bool changed = false;
            const std::string popupId = std::string("##append_token_") + (label ? label : "value");
            ImGui::BeginDisabled(!hasChoices);
            if (ImGui::SmallButton(label))
                ImGui::OpenPopup(popupId.c_str());
            ImGui::EndDisabled();

            if (!hasChoices)
                return false;

            if (ImGui::BeginPopup(popupId.c_str()))
            {
                for (const std::string& choice : choices)
                {
                    if (ImGui::Selectable(choice.c_str()))
                    {
                        AppendDelimitedToken(value, std::string(prefix ? prefix : "") + choice + (suffix ? suffix : ""));
                        changed = true;
                        ImGui::CloseCurrentPopup();
                    }
                }
                ImGui::EndPopup();
            }
            return changed;
        }

