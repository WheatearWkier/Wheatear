        inline bool DrawRewardSummaryListEditor(YAML::Node root)
        {
            bool changed = false;
            YAML::Node summaries = EnsureSequence(root, "dungeonRewardSummary");
            EditorWidgets::SectionHeader(EditorLocale::Text("Dungeon Reward Summary", "地牢奖励摘要"),
                "Narrative reward lines shown by progression result pages.");

            int removeIndex = -1;
            for (size_t i = 0; i < summaries.size(); ++i)
            {
                ImGui::PushID(static_cast<int>(i));
                bool lineChanged = false;
                std::string value = ScalarText(summaries[i]);
                ImGui::TextDisabled("#%d", static_cast<int>(i + 1));
                lineChanged |= EditorWidgets::InputMultilineString("##summary",
                    value,
                    ImVec2(-1.0f, 70.0f),
                    std::max<size_t>(1024, value.size() + 256));
                lineChanged |= DrawRewardTokenButtons(value);
                ImGui::SameLine();
                if (ImGui::SmallButton(EditorLocale::Text("Remove", "移除")))
                    removeIndex = static_cast<int>(i);
                if (lineChanged)
                {
                    summaries[i] = value;
                    changed = true;
                }
                ImGui::Separator();
                ImGui::PopID();
            }

            if (removeIndex >= 0)
            {
                summaries.remove(removeIndex);
                changed = true;
            }

            if (ImGui::Button(EditorLocale::Text("Add Reward Summary", "添加奖励摘要")))
            {
                summaries.push_back("");
                changed = true;
            }
            return changed;
        }

