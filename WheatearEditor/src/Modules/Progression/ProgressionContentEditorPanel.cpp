        std::string SkillNodeId(const YAML::Node& node, size_t index)
        {
            const std::string id = ScalarText(node["id"]);
            return id.empty() ? "__missing_skill_id_" + std::to_string(index + 1) : id;
        }

        bool IsSyntheticSkillId(const std::string& id)
        {
            return id.rfind("__missing_skill_id_", 0) == 0;
        }

        int SkillNodeIndexFromId(const std::string& nodeId)
        {
            const size_t separator = nodeId.find('-');
            if (separator == std::string::npos || separator + 1 >= nodeId.size())
                return 0;

            try
            {
                return std::max(std::stoi(nodeId.substr(separator + 1)), 0);
            }
            catch (...)
            {
                return 0;
            }
        }

        bool ReadSkillNodePosition(const YAML::Node& node, ImVec2& position)
        {
            const YAML::Node value = node["position"];
            if (!value)
                return false;

            try
            {
                if (value.IsSequence() && value.size() >= 2)
                {
                    position.x = std::clamp(value[0].as<float>(position.x), 0.0f, 1.0f);
                    position.y = std::clamp(value[1].as<float>(position.y), 0.0f, 1.0f);
                    return true;
                }

                if (value.IsMap())
                {
                    position.x = std::clamp(value["x"].as<float>(position.x), 0.0f, 1.0f);
                    position.y = std::clamp(value["y"].as<float>(position.y), 0.0f, 1.0f);
                    return true;
                }
            }
            catch (...)
            {
                return false;
            }

            return false;
        }

        void WriteSkillNodePosition(YAML::Node node, float x, float y)
        {
            YAML::Node position(YAML::NodeType::Map);
            position["x"] = std::clamp(x, 0.0f, 1.0f);
            position["y"] = std::clamp(y, 0.0f, 1.0f);
            node["position"] = position;
        }

        std::string Shorten(std::string text, size_t maxLength)
        {
            if (text.size() <= maxLength)
                return text;
            if (maxLength <= 3)
                return text.substr(0, maxLength);
            return text.substr(0, maxLength - 3) + "...";
        }

        bool SkillNodeIdExists(const YAML::Node& skillNodes, const std::string& id)
        {
            if (!skillNodes || !skillNodes.IsSequence())
                return false;

            for (size_t i = 0; i < skillNodes.size(); ++i)
            {
                YAML::Node node = skillNodes[i];
                if (node.IsMap() && ScalarText(node["id"]) == id)
                    return true;
            }
            return false;
        }

        std::string MakeUniqueSkillNodeId(const YAML::Node& skillNodes, const std::string& base)
        {
            if (!SkillNodeIdExists(skillNodes, base))
                return base;

            for (int i = 2; i < 10000; ++i)
            {
                const std::string candidate = base + "_" + std::to_string(i);
                if (!SkillNodeIdExists(skillNodes, candidate))
                    return candidate;
            }

            return base + "_copy";
        }

        std::unordered_map<std::string, SkillFallbackLayout> BuildFallbackSkillTreeLayout(const std::vector<SkillGraphNode>& nodes)
        {
            std::unordered_map<std::string, SkillFallbackLayout> result;
            const auto core = std::find_if(nodes.begin(), nodes.end(), [](const SkillGraphNode& node)
            {
                return node.Id == kMagicSwordCoreNodeId;
            });
            if (core == nodes.end())
                return result;

            result[kMagicSwordCoreNodeId] = { "", { 0.50f, 0.50f } };
            if (std::find_if(nodes.begin(), nodes.end(), [](const SkillGraphNode& node)
            {
                return node.Id == kMagicSwordLv2NodeId;
            }) != nodes.end())
            {
                result[kMagicSwordLv2NodeId] = { kMagicSwordCoreNodeId, { 0.50f, 0.36f } };
            }

            for (const SkillBranchLayout& layout : kSkillBranchLayouts)
            {
                const std::string branchPrefix = std::string(layout.Prefix) + "-";
                std::vector<const SkillGraphNode*> branchNodes;
                for (const SkillGraphNode& node : nodes)
                {
                    if (node.Id.rfind(branchPrefix, 0) == 0)
                        branchNodes.push_back(&node);
                }

                std::sort(branchNodes.begin(), branchNodes.end(), [](const SkillGraphNode* a, const SkillGraphNode* b)
                {
                    const int aIndex = SkillNodeIndexFromId(a->Id);
                    const int bIndex = SkillNodeIndexFromId(b->Id);
                    if (aIndex != bIndex)
                        return aIndex < bIndex;
                    return a->Id < b->Id;
                });

                std::string parent = kMagicSwordCoreNodeId;
                const size_t count = branchNodes.size();
                for (size_t i = 0; i < count; ++i)
                {
                    const float t = count > 1 ? static_cast<float>(i) / static_cast<float>(count - 1) : 0.0f;
                    const float radius = 0.11f + 0.045f * static_cast<float>(i + 1);
                    const float angle = (layout.BaseDegrees + layout.CurveDegrees * t) * kPi / 180.0f;
                    const float ringOffset = (i % 3 == 0 ? 0.014f : (i % 3 == 1 ? -0.006f : 0.006f));
                    const ImVec2 position = {
                        0.50f + std::cos(angle) * (radius + ringOffset),
                        0.50f + std::sin(angle) * (radius + ringOffset)
                    };

                    result[branchNodes[i]->Id] = { parent, position };
                    parent = branchNodes[i]->Id;
                }
            }

            return result;
        }

        std::vector<SkillGraphNode> BuildSkillGraphNodes(YAML::Node skillNodes)
        {
            std::vector<SkillGraphNode> nodes;
            if (!skillNodes || !skillNodes.IsSequence())
                return nodes;

            nodes.reserve(skillNodes.size());
            for (size_t i = 0; i < skillNodes.size(); ++i)
            {
                YAML::Node node = skillNodes[i];
                if (!node.IsMap())
                    continue;

                SkillGraphNode graphNode;
                graphNode.Index = i;
                graphNode.Node = node;
                graphNode.Id = SkillNodeId(node, i);
                graphNode.Name = ScalarText(node["name"]);
                graphNode.ParentId = ScalarText(node["parentId"]);
                graphNode.Branch = ScalarText(node["branch"]);
                graphNode.UnlockChapter = node["unlockChapter"].as<int>(1);
                graphNode.HasExplicitParent = MapContainsKey(node, "parentId");
                graphNode.HasExplicitPosition = ReadSkillNodePosition(node, graphNode.Position);
                nodes.push_back(std::move(graphNode));
            }

            const auto fallback = BuildFallbackSkillTreeLayout(nodes);
            for (SkillGraphNode& node : nodes)
            {
                if (auto it = fallback.find(node.Id); it != fallback.end())
                {
                    if (!node.HasExplicitParent)
                        node.ParentId = it->second.ParentId;
                    if (!node.HasExplicitPosition)
                        node.Position = it->second.Position;
                }
            }

            return nodes;
        }

        int FindSkillGraphIndex(const std::vector<SkillGraphNode>& nodes, const std::string& id)
        {
            for (size_t i = 0; i < nodes.size(); ++i)
            {
                if (nodes[i].Id == id)
                    return static_cast<int>(i);
            }
            return -1;
        }

