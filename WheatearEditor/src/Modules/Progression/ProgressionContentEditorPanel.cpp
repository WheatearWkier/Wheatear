        std::vector<std::string> BuildContentIds(const char* kind)
        {
            std::vector<std::string> ids;
            const auto& content = ProgressionContent::Get();
            if (std::string(kind ? kind : "") == "skill")
            {
                ids.reserve(content.SkillNodes.size());
                for (const auto& item : content.SkillNodes)
                    ids.push_back(item.Id);
            }
            else if (std::string(kind ? kind : "") == "equipment")
            {
                ids.reserve(content.Equipment.size());
                for (const auto& item : content.Equipment)
                    ids.push_back(item.Id);
            }
            else if (std::string(kind ? kind : "") == "equipmentSlot")
            {
                ids.reserve(content.EquipmentSlots.size());
                for (const auto& item : content.EquipmentSlots)
                    ids.push_back(item.Id);
            }
            else if (std::string(kind ? kind : "") == "dungeon")
            {
                ids.reserve(content.Dungeons.size());
                for (const auto& item : content.Dungeons)
                    ids.push_back(item.Id);
            }
            else if (std::string(kind ? kind : "") == "material")
            {
                ids.reserve(content.Materials.size());
                for (const auto& item : content.Materials)
                    ids.push_back(item.ItemId);
            }
            else if (std::string(kind ? kind : "") == "relationship")
            {
                ids.reserve(content.Relationships.size());
                for (const auto& item : content.Relationships)
                    ids.push_back(item.CharacterId);
            }

            ids.erase(std::remove_if(ids.begin(), ids.end(), [](const std::string& id)
            {
                return id.empty();
            }), ids.end());
            std::sort(ids.begin(), ids.end());
            ids.erase(std::unique(ids.begin(), ids.end()), ids.end());
            return ids;
        }

        bool DrawIdCombo(const char* label, std::string& value, const std::vector<std::string>& ids)
        {
            bool changed = false;
            ImGui::TextDisabled("%s", label ? label : "Id");
            ImGui::SameLine(150.0f);
            ImGui::PushID(label ? label : "id_combo");
            ImGui::SetNextItemWidth(260.0f);
            if (ImGui::BeginCombo("##value", value.empty() ? EditorLocale::Text("(none)", "(无)") : value.c_str()))
            {
                if (ImGui::Selectable(EditorLocale::Text("(none)", "(无)"), value.empty()))
                {
                    value.clear();
                    changed = true;
                }
                for (const std::string& id : ids)
                {
                    const bool selected = value == id;
                    const std::string itemLabel = EditorWidgets::LabelWithId(id, "progression_id:" + id);
                    if (ImGui::Selectable(itemLabel.c_str(), selected))
                    {
                        value = id;
                        changed = true;
                    }
                    if (selected)
                        ImGui::SetItemDefaultFocus();
                }
                ImGui::EndCombo();
            }
            ImGui::SameLine();
            if (ImGui::SmallButton(EditorLocale::Text("Clear", "清空")))
            {
                value.clear();
                changed = true;
            }
            ImGui::PopID();
            return changed;
        }

