        const char* NodeTypeLabel(const YAML::Node& node)
        {
            if (node.IsMap())
                return "map";
            if (node.IsSequence())
                return "list";
            if (node.IsScalar())
                return "value";
            if (node.IsNull())
                return "null";
            return "node";
        }

        std::string HumanizeKey(std::string key)
        {
            for (char& c : key)
            {
                if (c == '_' || c == '-')
                    c = ' ';
            }
            return key;
        }

        std::string LastPathSegment(const std::string& path)
        {
            const size_t slash = path.find_last_of('/');
            return slash == std::string::npos ? path : path.substr(slash + 1);
        }

        std::string ToLowerAscii(std::string value)
        {
            std::transform(value.begin(), value.end(), value.begin(), [](unsigned char c)
            {
                return static_cast<char>(std::tolower(c));
            });
            return value;
        }

        bool ContainsInsensitive(const std::string& value, const std::string& token)
        {
            return ToLowerAscii(value).find(ToLowerAscii(token)) != std::string::npos;
        }

        bool MapContainsKey(const YAML::Node& node, const std::string& key)
        {
            if (!node || !node.IsMap())
                return false;

            for (auto it = node.begin(); it != node.end(); ++it)
            {
                if (it->first.IsScalar() && it->first.as<std::string>() == key)
                    return true;
            }
            return false;
        }

        std::vector<std::string> MapKeysInOrder(const YAML::Node& node)
        {
            std::vector<std::string> keys;
            if (!node || !node.IsMap())
                return keys;

            for (auto it = node.begin(); it != node.end(); ++it)
            {
                if (it->first.IsScalar())
                    keys.push_back(it->first.as<std::string>());
            }
            return keys;
        }

        std::string ScalarText(const YAML::Node& node)
        {
            if (!node || !node.IsDefined() || node.IsNull())
                return {};

            try
            {
                return node.as<std::string>("");
            }
            catch (...)
            {
                return {};
            }
        }

